#!/bin/sh
# Prints the Homebrew formula of an Istok release.
#
# Usage: scripts/homebrew-formula.sh vX.Y.Z path/to/SHA256SUMS
#
# The release workflow writes the output to Formula/istok.rb of the tap
# repository vtimame/homebrew-tap.

set -eu

[ "$#" -eq 2 ] || {
  echo "usage: $0 vX.Y.Z SHA256SUMS" >&2
  exit 2
}

tag="$1"
sums="$2"

printf '%s\n' "$tag" | grep -Eq '^v[0-9]+\.[0-9]+\.[0-9]+$' || {
  echo "tag $tag is not vX.Y.Z" >&2
  exit 2
}

repo="${ISTOK_REPO:-vtimame/istok.sh}"
version="${tag#v}"
base="https://github.com/$repo/releases/download/$tag"

checksum() {
  value="$(awk -v asset="$1" '$2 == asset || $2 == "*" asset { print $1; exit }' "$sums")"
  printf '%s\n' "$value" | grep -Eq '^[0-9a-f]{64}$' || {
    echo "SHA256SUMS has no checksum for $1" >&2
    exit 1
  }

  printf '%s' "$value"
}

darwin_arm64="$(checksum istok_darwin_arm64.tar.gz)"
darwin_amd64="$(checksum istok_darwin_amd64.tar.gz)"
linux_arm64="$(checksum istok_linux_arm64.tar.gz)"
linux_amd64="$(checksum istok_linux_amd64.tar.gz)"

cat <<EOF
# Generated by scripts/homebrew-formula.sh in $repo for $tag.
class Istok < Formula
  desc "Local tasks, runs and checks for coding agents, with an MCP server"
  homepage "https://istok.sh"
  version "$version"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "$base/istok_darwin_arm64.tar.gz"
      sha256 "$darwin_arm64"
    end
    on_intel do
      url "$base/istok_darwin_amd64.tar.gz"
      sha256 "$darwin_amd64"
    end
  end

  on_linux do
    on_arm do
      url "$base/istok_linux_arm64.tar.gz"
      sha256 "$linux_arm64"
    end
    on_intel do
      url "$base/istok_linux_amd64.tar.gz"
      sha256 "$linux_amd64"
    end
  end

  def install
    bin.install "istok"
  end

  test do
    assert_match "v#{version}", shell_output("#{bin}/istok version")
  end
end
EOF
